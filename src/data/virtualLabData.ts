const ALIASES: Record<string, string> = {
  alcohol: "ethanol",
  ethanoic: "ch3cooh",
};

/** Bump when the lab matcher or catalogue wiring changes — used to detect stale bundles. */
export const LAB_RUNTIME = "chemvault-lab-v4";

export function canonicalId(id: string): string {
  const raw = id.trim().toLowerCase();
  return ALIASES[raw] ?? raw;
}

export function chemById(id: string): Chemical | undefined {
  const cid = canonicalId(id);
  return CHEMICALS.find((c) => c.id === id) ?? CHEMICALS.find((c) => canonicalId(c.id) === cid);
}

export function chemicalsIn(category: ChemCategory): Chemical[] {
  return CHEMICALS.filter((c) => c.category === category);
}

function setOf(ids: string[]): Set<string> {
  return new Set(ids.map(canonicalId));
}

function setsEqual(a: Set<string>, b: Set<string>): boolean {
  if (a.size !== b.size) return false;
  for (const id of a) if (!b.has(id)) return false;
  return true;
}

function exactReagentSet(reagents: string[], flask: Set<string>): boolean {
  return setsEqual(setOf(reagents), flask);
}

function reactionMatchesFlask(rxn: LabReaction, flask: Set<string>): boolean {
  if (exactReagentSet(rxn.reagents, flask)) return true;
  return (rxn.also ?? []).some((ids) => exactReagentSet(ids, flask));
}

function pickHit(hits: LabReaction[], heated: boolean): LabReaction | null {
  if (!hits.length) return null;
  if (heated) {
    return hits.find((h) => h.needsHeat) ?? hits.find((h) => !h.needsHeat) ?? null;
  }
  return hits.find((h) => !h.needsHeat) ?? null;
}

export type LabMatchTrace = {
  flask: string[];
  canonical: string[];
  equalSets: { id: string; reagents: string[]; also?: string[][]; needsHeat: boolean }[];
  selected: LabReaction | null;
};

/** Structured match trace — same four points the lab runtime logs during debug. */
export function traceLabMatch(ids: string[], heated: boolean): LabMatchTrace {
  const flask = setOf(ids);
  const hits = LAB_REACTIONS.filter((rxn) => reactionMatchesFlask(rxn, flask));
  return {
    flask: [...ids],
    canonical: [...flask].sort(),
    equalSets: hits.map((rxn) => ({
      id: rxn.id,
      reagents: rxn.reagents,
      also: rxn.also,
      needsHeat: rxn.needsHeat,
    })),
    selected: pickHit(hits, heated),
  };
}

export function matchLabReaction(ids: string[], heated: boolean): LabReaction | null {
  if (!ids.length) return null;
  return traceLabMatch(ids, heated).selected;
}

export function matchAlloy(ids: string[]): Alloy | null {
  const flask = setOf(ids);
  if (flask.size < 2) return null;

  const exact = ALLOYS.filter((a) => exactReagentSet(a.metals, flask));
  if (exact.length) {
    exact.sort((a, b) => b.metals.length - a.metals.length);
    return exact[0] ?? null;
  }

  if (flask.has("hg") && flask.size === 2) {
    const other = [...flask].find((id) => id !== "hg");
    return ALLOYS.find((a) => a.metals.includes("hg") && other && a.metals.includes(other)) ?? null;
  }
  return null;
}

